//! Strongly typed streaming event and WebSocket wire models.
//!
//! Provides canonical representations for the agent stream protocol,
//! session state synchronizations, and heartbeat messages.

use serde::{Deserialize, Serialize};

// ─── Agent Stream Event ───────────────────────────────────────────────────────

/// Strongly typed agent streaming event emitted during LLM generation and tool execution.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum AgentStreamEvent {
    /// Indicates start of a new conversational turn or prompt response.
    StartTurn {
        #[serde(rename = "sessionId", default)]
        session_id: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        model: Option<String>,
    },
    /// Text token generated by the model.
    Token {
        #[serde(rename = "sessionId", default)]
        session_id: String,
        content: String,
    },
    /// Extended thinking or chain-of-thought token generated by reasoning models.
    Thought {
        #[serde(rename = "sessionId", default)]
        session_id: String,
        content: String,
    },
    /// Agent tool invocation call.
    ToolCall {
        #[serde(rename = "sessionId", default)]
        session_id: String,
        #[serde(rename = "toolCallId")]
        tool_call_id: String,
        #[serde(rename = "toolName")]
        tool_name: String,
        #[serde(rename = "toolArgs", default)]
        tool_args: serde_json::Value,
    },
    /// Result received from a completed tool execution.
    ToolResult {
        #[serde(rename = "sessionId", default)]
        session_id: String,
        #[serde(rename = "toolCallId")]
        tool_call_id: String,
        #[serde(rename = "toolResult")]
        tool_result: serde_json::Value,
        #[serde(rename = "isError", default)]
        is_error: bool,
    },
    /// Multi-turn or multi-step execution intermediate completion checkpoint.
    StepComplete {
        #[serde(rename = "sessionId", default)]
        session_id: String,
        #[serde(rename = "stepIndex", default, skip_serializing_if = "Option::is_none")]
        step_index: Option<usize>,
    },
    /// Agent run completed successfully.
    Done {
        #[serde(rename = "sessionId", default)]
        session_id: String,
        #[serde(
            rename = "stopReason",
            default,
            skip_serializing_if = "Option::is_none"
        )]
        stop_reason: Option<String>,
    },
    /// Error encountered during agent run.
    Error {
        #[serde(rename = "sessionId", default)]
        session_id: String,
        error: String,
    },
    /// Agent execution aborted by user or timeout.
    Abort {
        #[serde(rename = "sessionId", default)]
        session_id: String,
    },
}

impl AgentStreamEvent {
    /// Returns the associated session ID for the event.
    pub fn session_id(&self) -> &str {
        match self {
            Self::StartTurn { session_id, .. } => session_id,
            Self::Token { session_id, .. } => session_id,
            Self::Thought { session_id, .. } => session_id,
            Self::ToolCall { session_id, .. } => session_id,
            Self::ToolResult { session_id, .. } => session_id,
            Self::StepComplete { session_id, .. } => session_id,
            Self::Done { session_id, .. } => session_id,
            Self::Error { session_id, .. } => session_id,
            Self::Abort { session_id } => session_id,
        }
    }

    /// Returns the snake_case event type name.
    pub fn event_type(&self) -> &'static str {
        match self {
            Self::StartTurn { .. } => "start_turn",
            Self::Token { .. } => "token",
            Self::Thought { .. } => "thought",
            Self::ToolCall { .. } => "tool_call",
            Self::ToolResult { .. } => "tool_result",
            Self::StepComplete { .. } => "step_complete",
            Self::Done { .. } => "done",
            Self::Error { .. } => "error",
            Self::Abort { .. } => "abort",
        }
    }

    pub fn start_turn(session_id: impl Into<String>, model: Option<String>) -> Self {
        Self::StartTurn {
            session_id: session_id.into(),
            model,
        }
    }

    pub fn token(session_id: impl Into<String>, content: impl Into<String>) -> Self {
        Self::Token {
            session_id: session_id.into(),
            content: content.into(),
        }
    }

    pub fn thought(session_id: impl Into<String>, content: impl Into<String>) -> Self {
        Self::Thought {
            session_id: session_id.into(),
            content: content.into(),
        }
    }

    pub fn tool_call(
        session_id: impl Into<String>,
        tool_call_id: impl Into<String>,
        tool_name: impl Into<String>,
        tool_args: serde_json::Value,
    ) -> Self {
        Self::ToolCall {
            session_id: session_id.into(),
            tool_call_id: tool_call_id.into(),
            tool_name: tool_name.into(),
            tool_args,
        }
    }

    pub fn tool_result(
        session_id: impl Into<String>,
        tool_call_id: impl Into<String>,
        tool_result: serde_json::Value,
        is_error: bool,
    ) -> Self {
        Self::ToolResult {
            session_id: session_id.into(),
            tool_call_id: tool_call_id.into(),
            tool_result,
            is_error,
        }
    }

    pub fn step_complete(session_id: impl Into<String>, step_index: Option<usize>) -> Self {
        Self::StepComplete {
            session_id: session_id.into(),
            step_index,
        }
    }

    pub fn done(session_id: impl Into<String>, stop_reason: Option<String>) -> Self {
        Self::Done {
            session_id: session_id.into(),
            stop_reason,
        }
    }

    pub fn error(session_id: impl Into<String>, error: impl Into<String>) -> Self {
        Self::Error {
            session_id: session_id.into(),
            error: error.into(),
        }
    }

    pub fn abort(session_id: impl Into<String>) -> Self {
        Self::Abort {
            session_id: session_id.into(),
        }
    }
}

// ─── Heartbeat / Pong Message ────────────────────────────────────────────────

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct PongMessage {
    pub action: String,
    pub timestamp: i64,
}

impl PongMessage {
    pub fn new() -> Self {
        Self {
            action: "PONG".to_string(),
            timestamp: chrono::Utc::now().timestamp_millis(),
        }
    }
}

impl Default for PongMessage {
    fn default() -> Self {
        Self::new()
    }
}

// ─── Session Sync Payload ────────────────────────────────────────────────────

/// Payload emitted over `session-sync` channel when a reconnecting client requests state catch-up.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Default)]
#[serde(rename_all = "camelCase")]
pub struct SessionSyncPayload {
    pub session_id: String,
    #[serde(default)]
    pub is_running: bool,
    #[serde(default)]
    pub replay_events: Vec<serde_json::Value>,
    #[serde(default)]
    pub full_assistant_text: String,
    #[serde(default)]
    pub full_thought_text: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub pending_tool: Option<serde_json::Value>,
}

// ─── Canonical Wire Message ──────────────────────────────────────────────────

/// Universal envelope for messages transmitted over the WebSocket hub (`/ws`).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(untagged)]
pub enum WireMessage {
    /// Agent execution stream event (`channel: "agent-event"`).
    AgentEvent {
        channel: String,
        data: AgentStreamEvent,
    },
    /// Replay and catch-up synchronization (`channel: "session-sync"`).
    SessionSync {
        channel: String,
        data: SessionSyncPayload,
    },
    /// Heartbeat response.
    Pong(PongMessage),
    /// Generic channel broadcast.
    Channel {
        channel: String,
        data: serde_json::Value,
    },
    /// Inbound or client-directed action.
    Action {
        action: String,
        #[serde(flatten)]
        extra: serde_json::Map<String, serde_json::Value>,
    },
}

impl WireMessage {
    pub fn agent_event(event: AgentStreamEvent) -> Self {
        Self::AgentEvent {
            channel: "agent-event".to_string(),
            data: event,
        }
    }

    pub fn session_sync(payload: SessionSyncPayload) -> Self {
        Self::SessionSync {
            channel: "session-sync".to_string(),
            data: payload,
        }
    }

    pub fn pong() -> Self {
        Self::Pong(PongMessage::new())
    }

    pub fn channel(channel: impl Into<String>, data: serde_json::Value) -> Self {
        Self::Channel {
            channel: channel.into(),
            data,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_agent_stream_event_serialization() {
        let event = AgentStreamEvent::token("sess-123", "Hello world");
        let json = serde_json::to_string(&event).unwrap();
        assert!(json.contains("\"type\":\"token\""));
        assert!(json.contains("\"sessionId\":\"sess-123\""));
        assert!(json.contains("\"content\":\"Hello world\""));

        let deserialized: AgentStreamEvent = serde_json::from_str(&json).unwrap();
        assert_eq!(deserialized, event);
        assert_eq!(deserialized.session_id(), "sess-123");
        assert_eq!(deserialized.event_type(), "token");
    }

    #[test]
    fn test_all_stream_event_variants() {
        let events = vec![
            AgentStreamEvent::start_turn("s1", Some("gpt-4o".into())),
            AgentStreamEvent::token("s1", "tok"),
            AgentStreamEvent::thought("s1", "reasoning"),
            AgentStreamEvent::tool_call(
                "s1",
                "call-1",
                "file_read",
                serde_json::json!({"path": "foo"}),
            ),
            AgentStreamEvent::tool_result(
                "s1",
                "call-1",
                serde_json::json!("file contents"),
                false,
            ),
            AgentStreamEvent::step_complete("s1", Some(1)),
            AgentStreamEvent::done("s1", Some("stop".into())),
            AgentStreamEvent::error("s1", "Something failed"),
            AgentStreamEvent::abort("s1"),
        ];

        for ev in events {
            let json = serde_json::to_string(&ev).unwrap();
            let parsed: AgentStreamEvent = serde_json::from_str(&json).unwrap();
            assert_eq!(parsed, ev);
            assert_eq!(parsed.session_id(), "s1");
        }
    }

    #[test]
    fn test_wire_message_roundtrip() {
        let ev = AgentStreamEvent::token("session-abc", "chunk");
        let wire = WireMessage::agent_event(ev);
        let json = serde_json::to_string(&wire).unwrap();
        assert!(json.contains("\"channel\":\"agent-event\""));

        let parsed: WireMessage = serde_json::from_str(&json).unwrap();
        match parsed {
            WireMessage::AgentEvent { channel, data } => {
                assert_eq!(channel, "agent-event");
                assert_eq!(data.session_id(), "session-abc");
            }
            _ => panic!("Expected AgentEvent variant"),
        }
    }

    #[test]
    fn test_pong_message() {
        let pong = PongMessage::new();
        let json = serde_json::to_string(&pong).unwrap();
        assert!(json.contains("\"action\":\"PONG\""));
        let parsed: PongMessage = serde_json::from_str(&json).unwrap();
        assert_eq!(parsed.action, "PONG");
    }

    #[test]
    fn test_session_sync_payload() {
        let payload = SessionSyncPayload {
            session_id: "s-1".into(),
            is_running: true,
            replay_events: vec![serde_json::json!({"foo": "bar"})],
            full_assistant_text: "Hello".into(),
            full_thought_text: "Thinking".into(),
            pending_tool: None,
        };
        let json = serde_json::to_string(&payload).unwrap();
        assert!(json.contains("\"sessionId\":\"s-1\""));
        assert!(json.contains("\"isRunning\":true"));
        let parsed: SessionSyncPayload = serde_json::from_str(&json).unwrap();
        assert_eq!(parsed, payload);
    }
}
